package orchestration

import (
	"errors"
	"regexp"
	"strings"
)

// NativeNameTarget keeps display metadata separate from all dispatch identities.
// No field here grants claim, handoff, dispatch or execution authorization.
type NativeNameTarget struct {
	GroupID        string `json:"group_id"`
	Role           string `json:"role"`
	Worker         string `json:"worker,omitempty"`
	Generation     int    `json:"generation"`
	Provider       string `json:"provider"`
	SessionID      string `json:"session_id,omitempty"`
	RuntimeAgentID string `json:"runtime_agent_id,omitempty"`
	AttemptID      string `json:"attempt_id,omitempty"`
	WorkerPath     string `json:"worker_path,omitempty"`
	T3ThreadID     string `json:"t3_thread_id,omitempty"`
	Execution      string `json:"execution"`
}
type SessionNameDirective struct {
	Target                 NativeNameTarget `json:"target"`
	DisplayName            string           `json:"display_name"`
	DelegateTitle          string           `json:"delegate_task_title"`
	Status                 string           `json:"status"`
	Verified               bool             `json:"verified"`
	IdentityAuthoritative  bool             `json:"identity_authoritative"`
	RequiredBeforeDispatch []string         `json:"required_before_dispatch"`
	RequiredAfterDispatch  []string         `json:"required_after_dispatch"`
	RequiredOnResume       []string         `json:"required_on_resume"`
	T3Status               string           `json:"t3_status"`
}

func SessionNamingDirective(g Group, target NativeNameTarget) (SessionNameDirective, error) {
	if target.Execution != "newSession" && target.Execution != "existingSession" {
		return SessionNameDirective{}, errors.New("execution must be newSession or existingSession")
	}
	if target.Provider != "codex" && target.Provider != "claude" {
		return SessionNameDirective{}, errors.New("selected provider must be codex or claude")
	}
	if target.Execution == "existingSession" && strings.TrimSpace(target.SessionID) == "" {
		return SessionNameDirective{}, errors.New("existingSession requires exact native session ID")
	}
	name, err := SessionName(g, target.Role, target.Worker, target.Generation)
	if err != nil {
		return SessionNameDirective{}, err
	}
	target.GroupID = g.GroupID
	return SessionNameDirective{Target: target, DisplayName: name, DelegateTitle: name, Status: "pending_native_verification", T3Status: "agent_tool_read_required_if_t3",
		RequiredBeforeDispatch: []string{
			"Complete fresh canonical contract/access/dispatch preflight; this metadata directive never authorizes dispatch.",
			"Check selected provider naming support; unknown/unsupported is not success. Never switch provider or execution mode.",
			"Use delegate_task.title exactly as generated when creating a T3 delegate; use native creation name option only if actually supported.",
			"Include this target, generated name and mandatory post-dispatch apply/verify instructions in the actual child prompt. Keep all runtime/attempt/handoff identities.",
		}, RequiredAfterDispatch: []string{
			"Capture actual provider-native session ID from native dispatch/current environment; never infer it from title or internal worker path.",
			"In that exact current managed session run orchestration session-name apply, then session-name verify. Preserve minimal official readback receipts; a request acknowledgement alone is insufficient.",
			"If T3 is used, call t3_thread_read on exact current thread, compare title; only if different call t3_thread_update with generated title, then reread. Report actual tool title and exact thread ID separately. Caller JSON is never T3 verification.",
			"Report partial, mismatch, timeout, unsupported or unverified evidence honestly to Controller. Do not declare naming complete with missing provider/T3 proof.",
		}, RequiredOnResume: []string{
			"Before existingSession dispatch re-read exact native target and retained group/role/worker/generation; same session resume never increments generation.",
			"After actual resume repeat current-session provider verification and T3 tool title readback; never reuse old receipts as current proof.",
			"Never bulk-rename other users, completed historical sessions, or infer a target from display metadata.",
		}}, nil
}

// Recognize only names already generated by SessionName, to prevent a resume
// from silently changing logical identity/generation. This never routes work.
const ManagedSessionNamePattern = `^D[0-9]{4}_[0-9]{2,}_(Root|Registrar|Controller|Worker_[A-Za-z][A-Za-z0-9_-]{0,39}_G[1-9][0-9]*)$`

var managedSessionNamePattern = regexp.MustCompile(ManagedSessionNamePattern)

func IsManagedSessionName(name string) bool { return managedSessionNamePattern.MatchString(name) }
